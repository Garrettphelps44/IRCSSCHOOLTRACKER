create policy "athletes_all" on public.athletes for all to anon, authenticated using (true) with check (true);

drop policy if exists "test_entries_all" on public.test_entries;
create policy "test_entries_all" on public.test_entries for all to anon, authenticated using (true) with check (true);

drop policy if exists "dress_logs_all" on public.dress_logs;
create policy "dress_logs_all" on public.dress_logs for all to anon, authenticated using (true) with check (true);

drop policy if exists "attendance_logs_all" on public.attendance_logs;
create policy "attendance_logs_all" on public.attendance_logs for all to anon, authenticated using (true) with check (true);

drop policy if exists "participation_logs_all" on public.participation_logs;
create policy "participation_logs_all" on public.participation_logs for all to anon, authenticated using (true) with check (true);

