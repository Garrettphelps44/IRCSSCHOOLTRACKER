-- IRCS Athlete Tracker schema
-- Run once in Supabase → SQL Editor → New query → Run

-- Athletes
create table if not exists public.athletes (
  id bigint generated by default as identity primary key,
  name text not null,
  period text not null,
  type text not null,
  sport text not null default '—',
  grad integer
);

-- Performance test entries
create table if not exists public.test_entries (
  id bigint generated by default as identity primary key,
  athlete_id bigint not null references public.athletes(id) on delete cascade,
  date date not null,
  bw numeric,
  fly numeric,
  jump numeric,
  rsi numeric,
  bsq numeric,
  bench numeric,
  tbdl numeric,
  sbdl numeric,
  m400 numeric,
  unique (athlete_id, date)
);

-- Dress code logs (one code per athlete per day)
create table if not exists public.dress_logs (
  id bigint generated by default as identity primary key,
  athlete_id bigint not null references public.athletes(id) on delete cascade,
  date date not null,
  code text not null,
  unique (athlete_id, date)
);

-- Attendance logs (one status per athlete per day)
create table if not exists public.attendance_logs (
  id bigint generated by default as identity primary key,
  athlete_id bigint not null references public.athletes(id) on delete cascade,
  date date not null,
  status text not null,
  unique (athlete_id, date)
);

-- Participation logs (one code per athlete per day)
-- LE = Lack of Effort, CNP = Choose Not to Participate
create table if not exists public.participation_logs (
  id bigint generated by default as identity primary key,
  athlete_id bigint not null references public.athletes(id) on delete cascade,
  date date not null,
  code text not null,
  unique (athlete_id, date)
);

-- Notes
create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  athlete_id bigint not null references public.athletes(id) on delete cascade,
  date date not null,
  issue text not null,
  action text not null,
  notes text not null default '',
  done boolean not null default false
);

-- Expose tables to the Data API (anon / authenticated)
grant select, insert, update, delete on public.athletes to anon, authenticated, service_role;
grant select, insert, update, delete on public.test_entries to anon, authenticated, service_role;
grant select, insert, update, delete on public.dress_logs to anon, authenticated, service_role;
grant select, insert, update, delete on public.attendance_logs to anon, authenticated, service_role;
grant select, insert, update, delete on public.participation_logs to anon, authenticated, service_role;
grant select, insert, update, delete on public.notes to anon, authenticated, service_role;

grant usage, select on all sequences in schema public to anon, authenticated, service_role;

alter table public.athletes enable row level security;
alter table public.test_entries enable row level security;
alter table public.dress_logs enable row level security;
alter table public.attendance_logs enable row level security;
alter table public.participation_logs enable row level security;
alter table public.notes enable row level security;

-- Open policies (no login). Tighten later if you add Auth.
